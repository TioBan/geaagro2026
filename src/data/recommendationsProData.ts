// Calculation Functions
export function calculateIGF(soil: SoilAnalysisExtended): number {
  let score = 50;

  // 1. Chemical V% score (Ideal: 65-75%)
  if (soil.baseSaturationPercent >= 65 && soil.baseSaturationPercent <= 75) score += 15;
  else if (soil.baseSaturationPercent >= 50) score += 10;
  else score -= 10;

  // 2. Aluminum saturation m%
  if (soil.aluminumSaturationPercent <= 5) score += 10;
  else if (soil.aluminumSaturationPercent > 20) score -= 15;

  // 3. Organic Matter (g/dm³)
  if (soil.organicMatterGKg >= 30) score += 10;
  else if (soil.organicMatterGKg >= 20) score += 6;

  // 4. Phosphorus (Resina mg/dm³)
  if (soil.pResina >= 25) score += 10;
  else if (soil.pResina >= 15) score += 5;
  else score -= 5;

  // 5. Potássio (cmolc/dm³)
  if (soil.kCmolc >= 0.3) score += 10;
  else if (soil.kCmolc >= 0.18) score += 5;

  // 6. Biological BioAS
  if (soil.betaGlucosidaseActivity && soil.betaGlucosidaseActivity > 120) score += 5;
  if (soil.arylsulfataseActivity && soil.arylsulfataseActivity > 60) score += 5;

  return Math.min(100, Math.max(10, Math.round(score)));
}

