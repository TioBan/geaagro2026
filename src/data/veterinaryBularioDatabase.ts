/**
 * Calculates required dose in mL or units based on species and animal weight
 */
export function calculateProductDose(
  product: VeterinaryProduct,
  species: string,
  weightKg: number
): { doseFormatted: string; notes?: string } | null {
  if (!product.dosageCalculation || product.dosageCalculation.length === 0) {
    return null;
  }

  // Find exact rule for species or first matching
  const rule =
    product.dosageCalculation.find((r) => r.species.toLowerCase() === species.toLowerCase()) ||
    product.dosageCalculation[0];

  if (rule.fixedDosePerAnimal) {
    return {
      doseFormatted: rule.fixedDosePerAnimal,
      notes: rule.notes,
    };
  }

  if (rule.mlPer100Kg) {
    const ml = (weightKg / 100) * rule.mlPer100Kg;
    return {
      doseFormatted: `${ml.toFixed(1).replace('.0', '')} mL`,
      notes: rule.notes,
    };
  }

  if (rule.mlPer50Kg) {
    const ml = (weightKg / 50) * rule.mlPer50Kg;
    return {
      doseFormatted: `${ml.toFixed(1).replace('.0', '')} mL`,
      notes: rule.notes,
    };
  }

  if (rule.mlPer10Kg) {
    const ml = (weightKg / 10) * rule.mlPer10Kg;
    return {
      doseFormatted: `${ml.toFixed(1).replace('.0', '')} mL`,
      notes: rule.notes,
    };
  }

  return null;
}
