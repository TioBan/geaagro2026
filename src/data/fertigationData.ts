    cloggingMechanism: 'Zero precipitação. Solução completamente solúvel.',
    dripperImpactPercent: 0,
    mixingOrderRule: '1º Adicionar o sal de menor solubilidade sob agitação; 2º Adicionar o segundo produto até completa dissolução.',
